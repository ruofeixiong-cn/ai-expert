# ── 检索 ─────────────────────────────────────────────────────
#
# ⚠️ gte-rerank-v2 的分数分布偏低：绝对值低不代表区分度差。
#    阈值按直觉设 0.5/0.7 会把所有召回结果滤光，表现为"专家什么都不知道"，
#    而链路每一步看起来都正常 —— 这是这个项目最难排查的一类故障。
#
# 0.05 → 0.15（2026-09-10，M6 黄金问答集校准，26 道题一次召回扫全曲线）：
#
#   阈值    covered 召回保留    uncovered 正确拦下
#   0.05        14/14 100%          2/12  17%   ← 旧值
#   0.12        14/14 100%         10/12  83%
#   0.15        14/14 100%         12/12 100%   ← 新值
#   0.20        12/14  86%         12/12 100%
#
#   分数分布：covered 最低 0.1874，uncovered 最高 0.1459，间隔仅 0.0415。
#
# 0.05 的代价是每个"他没讲过"的问题都要白跑一次生成模型 —— 花钱，
# 而且给了模型一个夹带世界知识的机会（实测 12 道里漏了 2 道）。
#
# ⚠️ 间隔只有 0.0415，样本 26 道、单一语料。**换语料或换 embedding 模型
#    必须重跑 `REAL_LLM=1 SWEEP=1 make eval` 重新校准**，不要照抄这个数。
#
# ⚠️ backend 的 BLINDSPOT_CONFIDENCE 与本值同源且【应当相等】——
#    "没过闸门"和"这是个盲区"是同一个判断。见 docs/adr/001。
RERANK_MIN_SCORE = 0.15


def count_tokens(text: str) -> int:
    """
    token 数的近似值。

    没有引真 tokenizer 是刻意的：精确计数对切分质量的影响，远小于
    "每个切片带标题路径前缀"这一条。等 M6 有黄金问答集能量化了再换，
    换的时候只动这一个函数。

    经验值：qwen 的 BPE 对中文约 1 字 1 token，对英文约 4 字符 1 token。
    这里略微高估（偏保守）—— 宁可切片小一点，也不要超模型上下文。
    """
    cjk = sum(1 for ch in text if "一" <= ch <= "鿿")
    return int(cjk + (len(text) - cjk) * 0.25)
