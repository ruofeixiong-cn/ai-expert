# ── 切分 ─────────────────────────────────────────────────────
TARGET_TOKENS = 500
MIN_TOKENS = 120          # 低于此值的切片尝试与相邻块合并（太碎的切片向量质量差）
MAX_TOKENS = 700          # 超过则硬切
OVERLAP_RATIO = 0.12      # 同一小节内相邻切片的重叠比例

# ── 成本护栏 ──────────────────────────────────────────────────
MAX_CHUNKS_PER_BUILD = 2000
EMBED_BATCH_SIZE = 10     # 百炼单次批量上限，实测值

# ── 检索（M3 用，先放这里免得又开一个文件）──────────────────
# ⚠️ gte-rerank-v2 的分数分布偏低：实测高度相关文档 0.2956、无关 0.0059。
#    阈值按直觉设 0.5/0.7 会把所有召回结果滤光，表现为"专家什么都不知道"。
RERANK_MIN_SCORE = 0.05


def count_tokens(text: str) -> int:
    """
    token 数的近似值。

    没有引真 tokenizer 是刻意的：精确计数对切分质量的影响，远小于
    "每个切片带标题路径前缀"这一条。等 M6 有黄金问答集能量化了再换，
    换的时候只动这一个函数。

    经验值：qwen 的 BPE 对中文约 1 字 1 token，对英文约 4 字符 1 token。
    这里略微高估（偏保守）—— 宁可切片小一点，也不要超模型上下文。
    """
    cjk = sum(1 for ch in text if "一" <= ch <= "鿿")
    return int(cjk + (len(text) - cjk) * 0.25)
